"""Pick the traces the homepage pulses run along.

Reads out/pcbhero.traces.json (written when the pcbhero scene is rendered with
the trace export) and writes assets/js/pcb-traces.js. Keeps longer traces in
the near and middle board, at most one per bundle of parallel traces.

    python3 tools/renders/pcb_traces.py
"""
import json, math, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
src = json.load(open(os.path.join(HERE, "out", "pcbhero.traces.json")))

def start(t):
    m = re.match(r"M([\d.-]+) ([\d.-]+)", t["d"]); return float(m.group(1)), float(m.group(2))

picked = []
for t in sorted(src, key=lambda t: -t["len"]):
    if t["len"] < 200 or t["depth"] < -8:
        continue
    x, y = start(t)
    if any(math.hypot(x - px, y - py) < 110 for px, py in (start(p) for p in picked)):
        continue
    picked.append(t)
    if len(picked) >= 22:
        break

out = [{"d": t["d"], "len": t["len"]} for t in picked]
dst = os.path.join(HERE, "..", "..", "assets", "js", "pcb-traces.js")
with open(dst, "w") as f:
    f.write("/* Generated by tools/renders/pcb_traces.py from the pcbhero render. Paths are in\n   2400 x 1100 image pixels. Don't edit by hand; re-render and re-run instead. */\n")
    f.write("window.PCB_TRACES = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(len(src), "traces,", len(out), "picked")
